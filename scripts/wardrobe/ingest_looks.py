"""Ingest generated wardrobe images into the app.

Input: a folder of images named {characterId}__{lookId}.(png|jpg|jpeg|webp); lookId
'signature' (or 'base') is the character's signature look.
For each: remove the background (rembg isnet-general-use), keep the largest figure,
register it on the shared 680x1020 stage canvas (same scale + floor line as every
other cut-out), save public/influencer/looks/{characterId}/{lookId}.webp.
Then rewrites src/features/influencer/looks.generated.ts from what's on disk.

Usage: python3 scripts/wardrobe/ingest_looks.py <folder> [--force]
       python3 scripts/wardrobe/ingest_looks.py --index-only
Needs: pip install rembg onnxruntime pillow scipy numpy
"""
import argparse, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOOKS = ROOT / 'public/influencer/looks'
GEN = ROOT / 'src/features/influencer/looks.generated.ts'
W, H = 680, 1020
FIG_H = int(H * 0.93)
NAME = re.compile(r'^([a-z0-9-]+)__([a-z0-9-]+)$')


def known_ids():
    chars = set(re.findall(r"\{ id: '([a-z0-9-]+)', name:", (ROOT / 'src/features/influencer/catalog.ts').read_text()))
    looks = set(re.findall(r"^\s{4}id: '([a-z-]+)',", (ROOT / 'src/features/influencer/wardrobe.ts').read_text(), re.M))
    return chars, looks | {'base'}


def cut(path, session):
    import numpy as np
    from PIL import Image
    from rembg import remove
    from scipy import ndimage
    im = Image.open(path).convert('RGB')
    c = remove(im, session=session, post_process_mask=True)
    arr = np.array(c)
    lab, n = ndimage.label(arr[:, :, 3] > 24)
    if n > 1:
        sizes = ndimage.sum(np.ones_like(lab), lab, range(1, n + 1))
        keep = ndimage.binary_dilation(lab == 1 + int(np.argmax(sizes)), iterations=3)
        arr[:, :, 3] = np.where(keep, arr[:, :, 3], 0)
        c = Image.fromarray(arr)
    fig = c.crop(c.getbbox())
    k = FIG_H / fig.height
    fig = fig.resize((max(1, int(fig.width * k)), FIG_H), Image.LANCZOS)
    if fig.width > W:  # very wide pose: fit width instead
        k = W / fig.width
        fig = fig.resize((W, int(fig.height * k)), Image.LANCZOS)
    canvas = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    canvas.alpha_composite(fig, ((W - fig.width) // 2, H - fig.height - int(H * 0.02)))
    return canvas


def write_index():
    data = {}
    for f in sorted(LOOKS.glob('*/*.webp')):
        data.setdefault(f.parent.name, {})[f.stem] = f'/influencer/looks/{f.parent.name}/{f.name}'
    GEN.write_text(
        '// Generated by scripts/wardrobe/ingest_looks.py. Do not edit by hand.\n'
        "// characterId -> lookId ('base' = signature) -> image path\n"
        f'export const LOOK_RENDERS: Record<string, Record<string, string>> = {json.dumps(data, indent=2)};\n')
    print(f'index: {sum(len(v) for v in data.values())} looks across {len(data)} characters -> {GEN.relative_to(ROOT)}')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('folder', nargs='?')
    ap.add_argument('--force', action='store_true')
    ap.add_argument('--index-only', action='store_true')
    a = ap.parse_args()
    if not a.index_only:
        if not a.folder:
            sys.exit('folder required')
        from rembg import new_session
        session = new_session('isnet-general-use')
        chars, looks = known_ids()
        files = [p for p in sorted(Path(a.folder).iterdir()) if p.suffix.lower() in {'.png', '.jpg', '.jpeg', '.webp'}]
        for p in files:
            m = NAME.match(p.stem.lower())
            if not m:
                print(f'skip (name): {p.name}'); continue
            cid, look = m.group(1), 'base' if m.group(2) == 'signature' else m.group(2)
            if cid not in chars or look not in looks:
                print(f'skip (unknown character/look): {p.name}'); continue
            dst = LOOKS / cid / f'{look}.webp'
            if dst.exists() and not a.force:
                print(f'exists: {dst.relative_to(ROOT)}'); continue
            dst.parent.mkdir(parents=True, exist_ok=True)
            cut(p, session).save(dst, 'WEBP', quality=86, method=6)
            print(f'ok: {cid} / {look}', flush=True)
    write_index()


if __name__ == '__main__':
    main()
