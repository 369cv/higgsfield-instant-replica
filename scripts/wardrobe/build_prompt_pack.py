"""Build the Wardrobe prompt pack for any image agent (arena.ai, ChatGPT, etc.).

Reads characters and outfits from the TS source plus vault image URLs, assigns
a signature + 3 looks per character, and writes:
  docs/wardrobe/assignments.json      machine-readable job list
  docs/wardrobe/arena-prompt-pack.md  paste-ready messages, one batch per message
Usage: python3 scripts/wardrobe/build_prompt_pack.py [--site https://halalfans.me] [--per-batch 8]
"""
import argparse, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ap = argparse.ArgumentParser()
ap.add_argument('--site', default='https://halalfans.me')
ap.add_argument('--per-batch', type=int, default=8)
ap.add_argument('--looks', type=int, default=3)
a = ap.parse_args()

cat_src = (ROOT / 'src/features/influencer/catalog.ts').read_text()
chars = re.findall(r"\{ id: '([a-z0-9-]+)', name: \"([^\"]+)\" \}", cat_src)
wd = (ROOT / 'src/features/influencer/wardrobe.ts').read_text()
outfits = [
    dict(id=i, name=n, category=c, job=j, description=re.sub(r"\s+", ' ', d))
    for i, n, c, j, d in re.findall(
        r"id: '([a-z-]+)',\s+name: '([^']+)',\s+category: '(\w+)',\s+sourceJobId: '([0-9a-f-]+)',\s+description:\s+'([^']+)'", wd)
]
vault = {it['id']: it for it in json.loads((ROOT / 'public/data/soul-generations.json').read_text())['items']}
for o in outfits:
    it = vault.get(o['job'], {})
    o['ref'] = it.get('fullImageUrl') or it.get('imageUrl') or ''

POSE = ('Full-body, front-facing studio photo, 2:3 portrait: standing straight, facing camera, arms relaxed at the sides, '
        'feet together, centered, head-to-toe in frame with a small margin above the head and below the feet. '
        'Plain seamless light grey background, soft even daylight, photorealistic skin and fabric detail. '
        'One person only. No text, logos or watermark.')

def prompt(name, o=None):
    if o is None:
        return (f"Recreate {name} from the character sheet in her own signature outfit from the sheet, at the highest quality. "
                f"Keep her exact face, skin tone, hair, body shape and height. {POSE}")
    return (f"Dress {name} (character sheet) in exactly this outfit (outfit reference): {o['description']}. "
            f"Use only the clothing from the outfit reference, never its model's face, hair or body. "
            f"Keep {name}'s exact face, skin tone, hair, body shape and height. {POSE}")

n = len(outfits)
jobs = []
for i, (cid, name) in enumerate(chars):
    sheet = f"{a.site}/influencer/characters/{cid}.webp"
    jobs.append(dict(file=f"{cid}__signature.png", character=cid, look='base', sheet=sheet, outfit_ref=None, prompt=prompt(name)))
    step = max(1, n // a.looks)
    for k in range(a.looks):  # spread across categories
        o = outfits[(i + k * step) % n]
        jobs.append(dict(file=f"{cid}__{o['id']}.png", character=cid, look=o['id'], sheet=sheet, outfit_ref=o['ref'], prompt=prompt(name, o)))

out = ROOT / 'docs/wardrobe'
out.mkdir(parents=True, exist_ok=True)
(out / 'assignments.json').write_text(json.dumps(jobs, indent=2))

md = [
    '# Wardrobe prompt pack', '',
    f'{len(chars)} characters × (signature + {a.looks} looks) = **{len(jobs)} images**. '
    'Generated by `scripts/wardrobe/build_prompt_pack.py`; rerun it after changing outfits.', '',
    '## How to use', '',
    '1. Paste **Message 0** into the image agent once.',
    f'2. Paste each batch message ({a.per_batch} images each) and wait for the results.',
    '3. Download every image with the exact file name given, into one folder.',
    '4. Run `python3 scripts/wardrobe/ingest_looks.py <folder>`: it cuts out the background, lines every look up on the stage and registers it in the Wardrobe.', '',
    '## Message 0: setup (paste once)', '', '```text',
    'You are generating a fashion wardrobe for a cast of virtual influencers. For every job I send you:',
    '- Image A is the character sheet (face close-up on the left, full body on the right). It defines who she is.',
    '- Image B (when given) is an outfit reference. Take ONLY the clothing, shoes and accessories from it.',
    '- Output one photorealistic image per job, 2:3 portrait, full body head to toe, front-facing, arms relaxed at the sides,',
    '  feet together, centered, plain seamless light grey background, soft even daylight. Same pose, scale and camera height every time.',
    '- Keep the character identical across all her images: face, skin tone, hair, body shape, height.',
    '- No text, logos, watermarks or extra people.',
    '- Name each output exactly as the job\'s file name, and give me a download link for every image.',
    'Reply "ready" and wait for the first batch.', '```', '',
]
for b in range(0, len(jobs), a.per_batch):
    batch = jobs[b:b + a.per_batch]
    md += [f'## Batch {b // a.per_batch + 1} ({b + 1}–{b + len(batch)})', '', '```text', f'Batch {b // a.per_batch + 1}. Generate these {len(batch)} images:', '']
    for j in batch:
        md.append(f"FILE: {j['file']}")
        md.append(f"Image A (character sheet): {j['sheet']}")
        if j['outfit_ref']:
            md.append(f"Image B (outfit reference): {j['outfit_ref']}")
        md.append(f"PROMPT: {j['prompt']}")
        md.append('')
    md += ['```', '']
(out / 'arena-prompt-pack.md').write_text('\n'.join(md))
print(f"{len(chars)} characters, {len(outfits)} outfits, {len(jobs)} images -> {out}")
